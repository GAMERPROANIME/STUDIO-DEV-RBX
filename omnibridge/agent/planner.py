"""Deterministic planner: decomposes a goal into executable steps over the real tool catalogue."""
from __future__ import annotations

from dataclasses import dataclass, field

from .roles import role_for_tool


@dataclass
class PlanStep:
    id: str
    title: str
    tool: str
    args: dict = field(default_factory=dict)
    role: str = "coordinator"
    depends_on: list[str] = field(default_factory=list)
    acceptance: str = "Step completes without error"

    def to_dict(self) -> dict:
        return {"id": self.id, "title": self.title, "tool": self.tool, "args": self.args,
                "role": self.role, "dependsOn": self.depends_on, "acceptance": self.acceptance}


@dataclass
class Plan:
    goal: str
    steps: list[PlanStep]
    rationale: str

    def to_dict(self) -> dict:
        return {"goal": self.goal, "steps": [s.to_dict() for s in self.steps], "rationale": self.rationale}


_counter = 0


def _step(title: str, tool: str, args: dict, depends_on: list[str] | None = None,
          acceptance: str = "Step completes without error") -> PlanStep:
    global _counter
    _counter += 1
    return PlanStep(id=f"s{_counter}", title=title, tool=tool, args=args,
                    role=role_for_tool(tool), depends_on=depends_on or [], acceptance=acceptance)


def create_plan(goal: str, workspace: str = ".") -> Plan:
    global _counter
    _counter = 0
    g = goal.lower()
    steps: list[PlanStep] = []
    inspect = _step("Inspect current project state", "project_inspect", {"path": workspace}, [],
                    "Existing systems identified")
    steps.append(inspect)

    if any(k in g for k in ("roblox", "studio", "luau", "jeu", "game", "combat", "arena", "personnage", "character")):
        kb = _step("Retrieve Luau/Roblox knowledge", "knowledge_retrieve", {"query": goal, "limit": 6},
                   [inspect.id], "Relevant docs retrieved with citations")
        steps.append(kb)
        arch = _step("Design system architecture", "agent_compare_solutions", {
            "problem": goal,
            "solutions": [
                {"name": "ModuleScript services (ReplicatedStorage)",
                 "description": "Shared modules + RemoteEvents, standard Roblox pattern",
                 "pros": ["Standard", "Testable", "Réutilisable"], "cons": ["Plus de fichiers"]},
                {"name": "Monolithic Scripts", "description": "Scripts uniques par système",
                 "pros": ["Simple au départ"], "cons": ["Couplage fort", "Difficile à maintenir"]},
            ],
        }, [kb.id], "Architecture choisie avec compromis documentés")
        steps.append(arch)
        build = _step("Implement the Luau system (script on disk)", "file_update", {
            "path": "src/server/OmniBridgeFeature.server.luau",
            "content": f"--!strict\n-- Generated by OMNIBRIDGE for goal: {goal}\n"
                       "-- Replace this scaffold with the real implementation, then run code_analyze.\n"
                       "local ReplicatedStorage = game:GetService(\"ReplicatedStorage\")\n"
                       "local Feature = {}\n\n"
                       "function Feature.start(): ()\n\tprint(\"[OmniBridgeFeature] ready\")\nend\n\n"
                       "Feature.start()\n\nreturn Feature\n",
        }, [arch.id], "Fichier Luau écrit avec sauvegarde de l'ancienne version")
        steps.append(build)
        analyze = _step("Static analysis of generated Luau", "code_analyze",
                        {"path": "src/server/OmniBridgeFeature.server.luau"}, [build.id], "Aucune erreur bloquante")
        steps.append(analyze)
        test = _step("Run tests / playtest checks", "code_test",
                     {"path": "src/server/CombatServer.server.luau"}, [analyze.id],
                     "Tests passent ou écarts documentés")
        steps.append(test)
        review = _step("Review final result", "agent_review_result",
                       {"taskId": "pending", "stepId": test.id}, [test.id], "Bilan présenté")
        steps.append(review)
    elif any(k in g for k in ("recherche", "research", "documentation", "doc", "compare", "comparer", "web")):
        search = _step("Search web sources", "web_search", {"query": goal, "maxResults": 6},
                       [inspect.id], "Sources officielles identifiées")
        steps.append(search)
        compare = _step("Compare sources", "web_compare_sources", {"query": goal, "urls": []},
                        [search.id], "Contradictions signalées")
        steps.append(compare)
        kb = _step("Index findings into knowledge base", "knowledge_index",
                   {"source": "agent-research", "title": goal, "text": goal}, [compare.id], "Synthèse indexée")
        steps.append(kb)
    elif any(k in g for k in ("bug", "erreur", "error", "debug", "fix", "corriger")):
        diag = _step("Diagnose error", "error_diagnose", {"message": goal, "path": workspace},
                     [inspect.id], "Cause racine identifiée")
        steps.append(diag)
        fix = _step("Apply fix", "file_update", {"path": "src/fix.luau", "content": "-- fix placeholder\n"},
                    [diag.id], "Correction appliquée avec sauvegarde")
        steps.append(fix)
        test = _step("Verify fix", "code_test", {"path": "src/fix.luau"}, [fix.id], "Erreur disparue")
        steps.append(test)
    else:
        kb = _step("Retrieve relevant knowledge", "knowledge_retrieve", {"query": goal, "limit": 6},
                   [inspect.id], "Contexte récupéré")
        steps.append(kb)
        exec_step = _step("Execute core action", "file_list", {"path": workspace}, [kb.id], "Action exécutée")
        steps.append(exec_step)
        review = _step("Review result", "agent_review_result",
                       {"taskId": "pending", "stepId": exec_step.id}, [exec_step.id], "Bilan présenté")
        steps.append(review)

    return Plan(
        goal=goal, steps=steps,
        rationale=f"Plan généré par le planificateur déterministe OMNIBRIDGE ({len(steps)} étapes). "
                  "Boucle: ANALYSE → PLANIFICATION → RECHERCHE → EXÉCUTION → TEST → INSPECTION → "
                  "CORRECTION → VALIDATION. Chaque étape est checkpointée et annulable.",
    )
